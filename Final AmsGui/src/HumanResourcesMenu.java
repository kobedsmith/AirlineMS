    private void btnSearchEmployeeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchEmployeeActionPerformed
        String searchID = txtUpdateID.getText().trim();
        boolean found = false;
        
        if (searchID.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter an employee ID.");
            return;
        }
        
        try (BufferedReader br = new BufferedReader(new FileReader("employees.txt"))) {
            String line;
            
            while ((line = br.readLine()) != null) {
                if (line.trim().isEmpty()) {
                    continue;
                }
                
                String[] parts = line.split(", ");
                
                if (parts.length >= 7 && parts[2].equals(searchID)) {
                    txtUpdateName.setText(parts[0]);
                    txtUpdateAge.setText(parts[1]);
                    txtUpdateEmail.setText(parts[3]);
                    txtUpdateWorkNum.setText(parts[4]);
                    txtUpdateDept.setText(parts[5]);
                    txtUpdateSalary.setText(parts[6]);
                    
                    found = true;
                    break;
                }
            }
            
            if (!found) {
                JOptionPane.showMessageDialog(this, "Employee not found.");
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error reading employees.txt.");
            System.err.println("Error reading file: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSearchEmployeeActionPerformed

    private void btnUpdateEmployeeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateEmployeeActionPerformed
        String searchID = txtUpdateID.getText().trim();
        
        if (searchID.isEmpty()
                || txtUpdateName.getText().trim().isEmpty()
                || txtUpdateAge.getText().trim().isEmpty()
                || txtUpdateEmail.getText().trim().isEmpty()
                || txtUpdateWorkNum.getText().trim().isEmpty()
                || txtUpdateDept.getText().trim().isEmpty()
                || txtUpdateSalary.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please search for an employee and fill in all fields.");
            return;
        }
        
        boolean updated = false;
        StringBuilder updatedFile = new StringBuilder();
        
        try (BufferedReader br = new BufferedReader(new FileReader("employees.txt"))) {
            String line;
            
            while ((line = br.readLine()) != null) {
                if (line.trim().isEmpty()) {
                    continue;
                }
                
                String[] parts = line.split(", ");
                
                if (parts.length >= 7 && parts[2].equals(searchID)) {
                    String updatedLine = txtUpdateName.getText().trim() + ", "
                            + txtUpdateAge.getText().trim() + ", "
                            + searchID + ", "
                            + txtUpdateEmail.getText().trim() + ", "
                            + txtUpdateWorkNum.getText().trim() + ", "
                            + txtUpdateDept.getText().trim() + ", "
                            + txtUpdateSalary.getText().trim();
                    
                    updatedFile.append(updatedLine).append(System.lineSeparator());
                    updated = true;
                } else {
                    updatedFile.append(line).append(System.lineSeparator());
                }
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error reading employees.txt.");
            System.err.println("Error reading file: " + e.getMessage());
            return;
        }
        
        if (!updated) {
            JOptionPane.showMessageDialog(this, "Employee not found.");
            return;
        }
        
        try (BufferedWriter bw = new BufferedWriter(new FileWriter("employees.txt"))) {
            bw.write(updatedFile.toString());
            
            JOptionPane.showMessageDialog(this, "Employee information updated.");
            
            loadEmployeeRecords();
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error updating employees.txt.");
            System.err.println("Error writing file: " + e.getMessage());
        }
    }//GEN-LAST:event_btnUpdateEmployeeActionPerformed

