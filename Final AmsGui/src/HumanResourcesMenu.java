    private void btnHireEmployeeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHireEmployeeActionPerformed
        String name = txtHireName.getText().trim();
        String age = txtHireAge.getText().trim();
        String id = txtHireID.getText().trim();
        String email = txtHireEmail.getText().trim();
        String workNum = txtHireWorkNum.getText().trim();
        String department = txtHireDept.getText().trim();
        String salary = txtHireSalary.getText().trim();
        
        if (name.isEmpty()
                || age.isEmpty()
                || id.isEmpty()
                || email.isEmpty()
                || workNum.isEmpty()
                || department.isEmpty()
                || salary.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Pleasee fill in all employee fields.");
            return;
        }
        
        try {
            Integer.parseInt(age);
            Integer.parseInt(id);
            Integer.parseInt(salary);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Age, Employee ID, and Salary must be numbers.");
            return;
        }
        
        String newEmployee = name + ", "
                + age + ", "
                + id + ", "
                + email + ", "
                + workNum + ", "
                + department + ", "
                + salary;
        
        try (BufferedWriter bw = new BufferedWriter(new FileWriter("employees.txt", true))) {
            bw.newLine();
            bw.write(newEmployee);
            
            JOptionPane.showMessageDialog(this, "New employee hired.");
            
            txtHireName.setText("");
            txtHireAge.setText("");
            txtHireID.setText("");
            txtHireEmail.setText("");
            txtHireWorkNum.setText("");
            txtHireDept.setText("");
            txtHireSalary.setText("");
            
            loadEmployeeRecords();
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error updating employees.txt.");
            System.err.println("Error writing file: " + e.getMessage());
        }
    }//GEN-LAST:event_btnHireEmployeeActionPerformed

    private void btnFireEmployeeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFireEmployeeActionPerformed
        String fireID = txtFireID.getText().trim();
        
        if(fireID.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter an employee ID.");
            return;
        }
        
        int choice = JOptionPane.showConfirmDialog(this, "Are you sure you want to fire employee ID " + fireID + "?",
                "Confirm", JOptionPane.YES_NO_OPTION);
        
        if (choice != JOptionPane.YES_OPTION) {
            return;
        }
        
        boolean removed = false;
        StringBuilder updatedFile = new StringBuilder();
        
        try (BufferedReader br = new BufferedReader(new FileReader("employees.txt"))) {
            String line;
            
            while ((line = br.readLine()) != null) {
                if (line.trim().isEmpty()) {
                    continue;
                }
                
                String[] parts = line.split(", ");
                
                if (parts.length >= 7 && parts[2].trim().equals(fireID)) {
                    removed = true;
                    continue;
                }
                
                updatedFile.append(line).append(System.lineSeparator());
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error reading employees.txt");
            System.err.println("Error reading file: " + e.getMessage());
            return;
        }
        
        if (!removed) {
            JOptionPane.showMessageDialog(this, "Employee not found.");
            return;
        }
        
        try (BufferedWriter bw = new BufferedWriter(new FileWriter("employees.txt"))) {
            bw.write(updatedFile.toString());
            
            txtFireID.setText("");
            
            JOptionPane.showMessageDialog(this, "Employee fired successfully.");
            
            loadEmployeeRecords();
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error updating employees.txt.");
            System.err.println("Error writing file: " + e.getMessage());
        }
    }//GEN-LAST:event_btnFireEmployeeActionPerformed

    private void loadEmployeeRecords() {
        DefaultTableModel model = (DefaultTableModel) tblEmployees.getModel();
        model.setRowCount(0);
        
        try (BufferedReader br = new BufferedReader(new FileReader("employees.txt"))) {
            String line;
            
            while ((line = br.readLine()) != null) {
                if (line.trim().isEmpty()) {
                    continue;
                }
                
                String[] parts = line.split(", ");
                
                if (parts.length >= 7) {
                    String name = parts[0];
                    String id = parts[2];
                    String department = parts[5];
                    String salary = parts[6];
                    
                    model.addRow(new Object[]{name, id, department, salary});
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }
    
