    private void formWindowOpened(java.awt.event.WindowEvent evt) {//GEN-FIRST:event_formWindowOpened
        try {
            BufferedReader br = new BufferedReader(new FileReader("flights.txt"));
            BufferedReader br1 = new BufferedReader(new FileReader("purchasedTickets.txt"));

            String line;
    
            DefaultTableModel model = (DefaultTableModel) tblAvailableFlights.getModel();
            DefaultTableModel model1 = (DefaultTableModel) tblYourFlights.getModel();
    
            while ((line = br.readLine()) != null) {
                String[] rowData = line.split(",");
                model.addRow(rowData);
            }
            
            while ((line = br1.readLine()) != null) {
                if (line.toLowerCase().contains(passenger.getName().toLowerCase())) {
                    String[] rowData = line.split(",");
                    model1.addRow(rowData);
                }
            }
            
            br.close();
            br1.close();
        } catch (Exception e) {
            e.printStackTrace();
        }
        
    }//GEN-LAST:event_formWindowOpened

