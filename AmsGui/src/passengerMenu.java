    private void btnCancelBookingActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelBookingActionPerformed
        int selected = tblYourFlights.getSelectedRow();
        File input = new File("purchasedTickets.txt");
        File output = new File("temp.txt");
        
        String name = tblYourFlights.getValueAt(selected, 0).toString();
        String flightID = tblYourFlights.getValueAt(selected, 1).toString();
        String origin = tblYourFlights.getValueAt(selected, 2).toString();
        String destination = tblYourFlights.getValueAt(selected, 3).toString();
        String gate = tblYourFlights.getValueAt(selected, 4).toString();
        String departure = tblYourFlights.getValueAt(selected, 5).toString();
        String arrival = tblYourFlights.getValueAt(selected, 6).toString();
        
        //String lineToRemove = name + ", " + flightID + ", " + origin + ", " + destination + ", " + gate + ", " + departure + ", " + arrival;
        
        if (selected != -1) {
            DefaultTableModel model = (DefaultTableModel) tblYourFlights.getModel();
            int choice = JOptionPane.showConfirmDialog(this, "Confirm Cancellation.",
                "Confirm Deletion", JOptionPane.YES_NO_OPTION);
            if (choice == JOptionPane.YES_OPTION) {
                model.removeRow(selected);
                JOptionPane.showMessageDialog(this, "You should expect your refund in 2-3 business days.");
                try {
                    BufferedReader reader = new BufferedReader(new FileReader(input));
                    BufferedWriter writer = new BufferedWriter(new FileWriter(output));

                    String line;
                    boolean removed = false;
                    
                    while ((line = reader.readLine()) != null) {
                        String[] parts = line.split(",");

                        if (parts.length >= 7) {
                            if (parts[0].trim().equalsIgnoreCase(name.trim()) &&
                                parts[1].trim().equalsIgnoreCase(flightID.trim()) &&
                                parts[2].trim().equalsIgnoreCase(origin.trim()) &&
                                parts[3].trim().equalsIgnoreCase(destination.trim()) &&
                                parts[4].trim().equalsIgnoreCase(gate.trim()) &&
                                parts[5].trim().equalsIgnoreCase(departure.trim()) &&
                                parts[6].trim().equalsIgnoreCase(arrival.trim())) {

                                System.out.println("MATCH FOUND → REMOVING");
                                continue;
                            }
                        }
                        writer.write(line);
                        writer.newLine();
                    }
                    reader.close();
                    writer.close();
                } catch (Exception e) {
                    e.printStackTrace();
                }
                input.delete();
                output.renameTo(input);
            }
        } else {
            System.out.println("No row selected.");
        }
    }//GEN-LAST:event_btnCancelBookingActionPerformed

