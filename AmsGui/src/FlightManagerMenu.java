    private void btnRemoveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveActionPerformed
        // TODO add your handling code here:
        int selected = tblFlights.getSelectedRow();
        File input = new File("flights.txt");
        File output = new File("tempFlights.txt");
        
        String flightID = tblFlights.getValueAt(selected, 1).toString();
        String origin = tblFlights.getValueAt(selected, 2).toString();
        String destination = tblFlights.getValueAt(selected, 3).toString();
        String gate = tblFlights.getValueAt(selected, 4).toString();
        String departure = tblFlights.getValueAt(selected, 5).toString();
        String arrival = tblFlights.getValueAt(selected, 0).toString();
        
        
        //String lineToRemove = name + ", " + flightID + ", " + origin + ", " + destination + ", " + gate + ", " + departure + ", " + arrival;
        
        if (selected != -1) {
            DefaultTableModel model = (DefaultTableModel) tblFlights.getModel();
            int choice = JOptionPane.showConfirmDialog(this, "Confirm Cancellation.",
                "Confirm Deletion", JOptionPane.YES_NO_OPTION);
            if (choice == JOptionPane.YES_OPTION) {
                model.removeRow(selected);
                JOptionPane.showMessageDialog(this, "Flight canceled");
                try {
                    BufferedReader reader = new BufferedReader(new FileReader(input));
                    BufferedWriter writer = new BufferedWriter(new FileWriter(output));

                    String line;
                    boolean removed = false;
                    
                    while ((line = reader.readLine()) != null) {
                        String[] parts = line.split(",");

                        if (parts.length >= 7) {
                            if (parts[0].trim().equalsIgnoreCase(flightID.trim()) &&
                                parts[1].trim().equalsIgnoreCase(origin.trim()) &&
                                parts[2].trim().equalsIgnoreCase(destination.trim()) &&
                                parts[3].trim().equalsIgnoreCase(gate.trim()) &&
                                parts[4].trim().equalsIgnoreCase(departure.trim()) &&
                                parts[5].trim().equalsIgnoreCase(arrival.trim())) {

                                System.out.println("MATCH FOUND → REMOVING");
                                continue;
                            }
                        }
                        writer.write(line);
                        writer.newLine();
                    }
                    reader.close();
                    writer.close();
                } catch (Exception e) {
                    e.printStackTrace();
                }
                input.delete();
                output.renameTo(input);
            }
        } else {
            System.out.println("No row selected.");
        }
    }//GEN-LAST:event_btnRemoveActionPerformed

