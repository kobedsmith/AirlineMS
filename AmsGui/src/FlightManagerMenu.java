    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
            BufferedReader br = new BufferedReader(new FileReader("staffView.txt"));
            String line;
            String flightID = txtFlightIDView.getText();
            
            DefaultTableModel staff = (DefaultTableModel) tblStaff.getModel();
            staff.setNumRows(0);
            
            while ((line = br.readLine()) != null) {
                String[] rowData = line.split(" - ");
                if(line.toLowerCase().contains(flightID.toLowerCase())){
                    staff.addRow(rowData);
                }
            }
            
        } catch (Exception e){
            e.printStackTrace();
        }
        
        try {
            BufferedReader br = new BufferedReader(new FileReader("purchasedTickets.txt"));
            String line;
            String flightID = txtFlightIDView.getText();
            
            DefaultTableModel passangers = (DefaultTableModel) tblPassangers.getModel();
            passangers.setRowCount(0);
            
            while ((line = br.readLine()) != null) {
                String[] rowData = line.split(",");
                if(line.toLowerCase().contains(flightID.toLowerCase())){
                    passangers.addRow(rowData);
                }
            }
            
        } catch (Exception e){
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        String id = txtID.getText();
        String origin = txtOrigin.getText();
        String destination = txtDestination.getText();
        String gate = txtGate.getText();
        String departTime = txtDepartTime.getText();
        String arrivalTime = txtArrivalTime.getText(); 
                
        Flight flight = new Flight(id, origin, destination, gate, departTime, arrivalTime);

        try {

            FileWriter fw = new FileWriter("flights.txt", true);
            fw.write("\n" + id + ", " + origin + ", " + destination + ", " + gate + ", " + departTime + ", " + arrivalTime);
            fw.close();

            txtID.setText("");
            txtOrigin.setText("");
            txtDestination.setText("");
            txtGate.setText("");
            txtDepartTime.setText("");
            txtArrivalTime.setText("");

            JOptionPane.showMessageDialog(this, "New flight added");

            BufferedReader br = new BufferedReader(new FileReader("flights.txt"));
            String line;

            DefaultTableModel flights = (DefaultTableModel) tblFlights.getModel();

            flights.setRowCount(0);

            while ((line = br.readLine()) != null) {
                String[] rowData = line.split(",");
                flights.addRow(rowData);
            }
        } catch (IOException e) {
            System.err.println("Error updating file: " + e.getMessage());
        }
    }//GEN-LAST:event_btnAddActionPerformed

